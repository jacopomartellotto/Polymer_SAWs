"""Estimate nu from the pure asymptotic power law <Re2> = A*N^(2*nu)."""
import json
import numpy as np
import pandas as pd
from scipy.optimize import curve_fit
from scipy.stats import chi2 as chi2_distribution
from comparison_data import load_grid
from project_paths import ANALYSIS, CONFIG, PIVOT_SUMMARY, ROOT

#Law used to fit
def power_law(n, amplitude, nu):
    """Mean squared end-to-end distance in lattice units."""
    return amplitude * np.asarray(n, dtype=float)**(2 * nu)


#Return the Jacobian in order to obtain  a faster convergence
def power_law_jacobian(n, amplitude, nu):
    n = np.asarray(n, dtype=float)
    power = n**(2 * nu)
    return np.column_stack((power, 2 * amplitude * power * np.log(n)))


def format_nu_estimate(value, error):
    """Round a one-sigma error to one significant digit and match the value."""
    rounded_error = float(f"{error:.1g}")
    decimals = max(0, -int(np.floor(np.log10(rounded_error))))
    return f"{value:.{decimals}f}" + r"\pm" + f"{rounded_error:.{decimals}f}"


def write_slide_results(results, protocol):
    """Keep the presentation's main fit values synchronized with the analysis."""
    lines = ["% Generated by scripts/estimate_nu.py; do not edit values by hand."]
    for name in ("simple", "pivot"):
        result = results[f"{name}_pure_Nmin_{int(protocol[name + '_N_min'])}"]
        for suffix, value in (
            ("Nu", format_nu_estimate(result["nu"], result["nu_sem"])),
            ("ReducedChi", f"{result['chi2_reduced']:.2f}"),
            ("Dof", str(result["dof"])),
        ):
            lines.append("\\newcommand{\\" + name + suffix + "}{" + value + "}")
    (ROOT / "slides" / "sampling_fit_results.tex").write_text(
        "\n".join(lines) + "\n", encoding="utf-8")


def fit(n, y, sem):
    n, y, sem = (np.asarray(v, dtype=float) for v in (n, y, sem))
    #check for errors 
    if (n.ndim != 1 or y.shape != n.shape or sem.shape != n.shape
            or len(n) <= 2):
        raise ValueError("Fit requires matching one-dimensional arrays and >2 points")
    if not all(np.all(np.isfinite(v)) and np.all(v > 0) for v in (n, y, sem)):
        raise ValueError("Lengths, means and SEMs must be finite and positive")

    # Fit the original observable directly, without a logarithmic transform.
    initial_amplitude = float(np.median(y / n**1.5)) #my p_0 based on theoretical knowledge
    
    popt, pcov = curve_fit(
        power_law, n, y, p0=(initial_amplitude, .75),
        sigma=sem, absolute_sigma=True, jac=power_law_jacobian,
        maxfev=20000, ftol=1e-12, xtol=1e-12, gtol=1e-12,
    )
    
    amplitude, nu = map(float, popt)
    #check for the fit
    if not np.all(np.isfinite(pcov)) or np.any(np.diag(pcov) <= 0):
        raise RuntimeError("The fit covariance is not finite and positive")
    #extract best fit parameter and calculate chi2
    amplitude_sem, nu_sem = map(float, np.sqrt(np.diag(pcov)))
    residuals = (y - power_law(n, amplitude, nu)) / sem
    chi2 = float(residuals @ residuals) #dot product
    dof = len(n) - 2 # -2 because we estimate two parameters
    
    
    # Local Gaussian covariance intervals, not profile-chi-square intervals.
    # absolute_sigma=True: never multiply pcov by chi2/dof.
    return {
        "A": amplitude, "A_sem": amplitude_sem,
        "nu": nu, "nu_sem": nu_sem,
        "covariance": pcov.tolist(), "parameter_order": ["A", "nu"],
        
        #confidene intervals 
        "ci68": [nu - nu_sem, nu + nu_sem],
        "ci95": [nu - 1.959963984540054 * nu_sem,
                 nu + 1.959963984540054 * nu_sem],
        
        
        "chi2": chi2, "dof": dof, "chi2_reduced": chi2 / dof,
        "p_value": float(chi2_distribution.sf(chi2, dof)),
        "N_min": int(n.min()), "N_max": int(n.max()), "points": len(n),
        "model": "A*N^(2*nu)", "method": "scipy.optimize.curve_fit",
        "absolute_sigma": True,
        "uncertainty": "Local Gaussian covariance; one-sigma statistical errors conditional on model and fit range; no chi-square rescaling",
    }


def main():
    protocol = json.loads(CONFIG.read_text(encoding="utf-8"))["analysis"]
    pivot = pd.read_csv(PIVOT_SUMMARY)
    pivot = pivot[pivot.N >= 200]
    results = {}
    pivot_nmins = sorted({200, 1000, 3000, 4000, 5000,
                          int(protocol["pivot_N_min"]), 7000})
    for nmin in pivot_nmins:
        subset = pivot[pivot.N >= nmin]
        results[f"pivot_pure_Nmin_{nmin}"] = fit(
            subset.N, subset.Re2_mean_mean, subset.Re2_mean_sem)
    grid = load_grid()
    grid = grid[grid.survivors >= 100]
    simple_nmins = sorted({4, 6, 8, 10, 12, 14, 16,
                           int(protocol["simple_N_min"])})
    for nmin in simple_nmins:
        subset = grid[grid.N >= nmin]
        results[f"simple_pure_Nmin_{nmin}"] = fit(
            subset.N, subset.Re2_mean, subset.Re2_sem)
    (ANALYSIS / "nu_estimates.json").write_text(json.dumps(results, indent=2))
    write_slide_results(results, protocol)
    print(json.dumps(results, indent=2))


if __name__ == "__main__":
    main()
