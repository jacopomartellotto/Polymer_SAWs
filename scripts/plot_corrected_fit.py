"""Reproducible backup-only Pivot fit with two finite-size corrections.

The primary thesis fits remain A*N**(2*nu). This supplementary comparison
uses all 21 measured Pivot lengths from 200 to 20000 with four free parameters.
"""
import json
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from scipy.optimize import curve_fit
from scipy.stats import chi2 as chi2_distribution

from figure_style import apply_style, error_points, save_figure, PIVOT_COLOR, INK
from project_paths import ANALYSIS, FIGURES, ROOT


def model(n, amplitude, nu, scaled_b, scaled_c):
    # Rescaling improves conditioning; physical b=1000*scaled_b and
    # c=1000**1.5*scaled_c. The physical model is unchanged.
    t = 1000 / np.asarray(n, dtype=float)
    return amplitude * n**(2*nu) * (1 + scaled_b*t + scaled_c*t**1.5)


def jacobian(n, amplitude, nu, scaled_b, scaled_c):
    t = 1000 / np.asarray(n, dtype=float)
    h = n**(2*nu)
    q = 1 + scaled_b*t + scaled_c*t**1.5
    return np.column_stack((h*q, 2*amplitude*h*q*np.log(n),
                            amplitude*h*t, amplitude*h*t**1.5))


def main():
    all_data = pd.read_csv(ANALYSIS / "comparison_three_observables.csv")
    all_data = all_data.dropna(subset=["Re2_Pivot_mean", "Re2_Pivot_sem"])
    all_data = all_data.sort_values("N")
    data = all_data[all_data.N >= 200]
    n = data.N.to_numpy(float)
    y = data.Re2_Pivot_mean.to_numpy(float)
    sem = data.Re2_Pivot_sem.to_numpy(float)
    candidates = []
    for initial_nu in (.74, .75, .76):
        popt, pcov = curve_fit(model, n, y, sigma=sem, absolute_sigma=True,
                               p0=(.77, initial_nu, 0, 0), jac=jacobian,
                               maxfev=50000, ftol=1e-12, xtol=1e-12, gtol=1e-12)
        residuals = (y-model(n, *popt))/sem
        candidates.append((float(residuals@residuals), popt, pcov))
    chi2, popt, pcov = min(candidates, key=lambda item: item[0])
    if max(item[0] for item in candidates)-chi2 > 1e-4:
        raise RuntimeError("Correction fit depends on the initial guess")
    transform = np.diag([1, 1, 1000, 1000**1.5])
    physical = transform@popt
    covariance = transform@pcov@transform.T
    errors = np.sqrt(np.diag(covariance))
    dof = len(n)-len(popt)
    result = dict(model="A*N^(2*nu)*(1+b/N+c/N^1.5)",
                  parameter_order=["A", "nu", "b", "c"],
                  parameters=physical.tolist(), sem=errors.tolist(),
                  covariance=covariance.tolist(), chi2=chi2, dof=dof,
                  chi2_reduced=chi2/dof, p_value=float(chi2_distribution.sf(chi2,dof)),
                  N_min=int(n.min()), N_max=int(n.max()), points=len(n),
                  method="scipy.optimize.curve_fit", absolute_sigma=True,
                  notes="Supplementary fit only. Fixed correction exponents 1 and 3/2; local one-sigma covariance errors, no chi-square rescaling.")
    (ANALYSIS / "backup_pivot_corrections.json").write_text(json.dumps(result,indent=2))
    apply_style()
    fig, ax = plt.subplots(figsize=(7.2,5.2),layout="constrained")
    xx = np.geomspace(n.min(),n.max(),600)
    ax.plot(xx,model(xx,*popt),color=INK,lw=1.2,label="Fit with corrections")
    outside = all_data[all_data.N < 200]
    error_points(ax,outside.N,outside.Re2_Pivot_mean,outside.Re2_Pivot_sem,
                 color="#6F87A1",marker="o",size=22,label="Outside fit",zorder=2)
    error_points(ax,n,y,sem,color=PIVOT_COLOR,marker="s",size=25,
                 label="Fit range",zorder=3)
    ax.set(xscale="log",yscale="log",xlabel=r"$N$",ylabel=r"$\langle R_e^2\rangle$")
    ax.legend(loc="upper left")
    save_figure(fig,FIGURES,"backup_pivot_corrections")
    plt.close(fig)
    # Generate numerical macros so rerendering data also updates the backup slide.
    lines = ["% Generated by scripts/plot_corrected_fit.py; do not edit values by hand."]
    for name, value, error in zip(("A","Nu","B","C"),physical,errors):
        decimals = max(0,-int(np.floor(np.log10(error))))
        lines.append(r"\newcommand{\corrected"+name+"}{"+
                     f"{value:.{decimals}f}"+r"\pm"+f"{error:.{decimals}f}"+"}")
    lines += [r"\newcommand{\correctedChi}{"+f"{chi2:.2f}"+"}",
              r"\newcommand{\correctedReducedChi}{"+f"{chi2/dof:.2f}"+"}",
              r"\newcommand{\correctedDof}{"+str(dof)+"}"]
    (ROOT/"slides"/"pivot_corrected_results.tex").write_text("\n".join(lines)+"\n")
    print(f"Backup corrected fit: {len(n)} lengths, nu={physical[1]:.9f} +/- {errors[1]:.9f}, chi2/dof={chi2/dof:.5f}")


if __name__ == "__main__":
    main()
